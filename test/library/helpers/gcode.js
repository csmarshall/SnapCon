// test/library/helpers/gcode.js — synthetic G-code shaped like the real
// library's files (OrcaSlicer 2.4.2 / Snapmaker Orca): header, thumbnails,
// EXCLUDE_OBJECT_DEFINE instances, a body, and a config block at the end.
"use strict";

const PNG_1x1 = Buffer.from("89504e470d0a1a0a0000000d4948445200000001000000010806000000" +
  "1f15c4890000000d4944415478da63f8ffff3f0005fe02fea7d6a4c30000000049454e44ae426082", "hex");

function thumb(w, h, data) {
  const b64 = data.toString("base64");
  const lines = [];
  for (let i = 0; i < b64.length; i += 78) lines.push("; " + b64.slice(i, i + 78));
  return [";", `; thumbnail begin ${w}x${h} ${b64.length}`, ...lines, "; thumbnail end", ";"];
}

// objects: [["Kitty.stl", copies], ...]; bodyBytes pads the print body; the
// config block can be omitted (config: false) or put somewhere else by the caller.
function gcodeFile({ printerModel = "Snapmaker U1", settingsId = null, compatible = null, generic = false, objects = [["Part.stl", 1]],
  bodyBytes = 2000, config = true, extraConfig = [], generator = "OrcaSlicer 2.4.2", thumbData = PNG_1x1 } = {}) {
  const head = [
    "; HEADER_BLOCK_START",
    `; generated by ${generator} on 2026-09-22 at 00:01:58`,
    "; total layer number: 249",
    "; HEADER_BLOCK_END",
    "",
    "; THUMBNAIL_BLOCK_START",
    ...thumb(48, 48, PNG_1x1),
    ...thumb(300, 300, thumbData),
    "; THUMBNAIL_BLOCK_END",
    "",
  ];
  const defs = [];
  objects.forEach(([name, copies], id) => { for (let c = 0; c < copies; c++) defs.push(`EXCLUDE_OBJECT_DEFINE NAME=${name.replace(/ /g, "_")}_id_${id}_copy_${c} CENTER=1,2 POLYGON=[[1,2],[3,4]]`); });
  const body = ["; EXECUTABLE_BLOCK_START", ...defs, "G28", "G1 X10 Y10 F3000"];
  objects.forEach(([name], id) => body.push(`; printing object ${name} id:${id} copy 0`, "G1 X20 Y20 E1", "; stop printing object " + name));
  let pad = "";
  while (pad.length < bodyBytes) pad += "G1 X1.234 Y5.678 E0.0123\n";
  const cfg = config ? [
    "; CONFIG_BLOCK_START",
    "; filament used [g] = 104.55",
    "; estimated printing time (normal mode) = 5h 41m 12s",
    "; filament_colour = #FF0000",
    "; filament_type = PLA",
    "; layer_height = 0.2",
    "; nozzle_diameter = 0.4",
    `; printer_model = ${generic ? "Generic Klipper Printer" : printerModel}`,
    ...(settingsId ? [`; printer_settings_id = ${settingsId}`] : []),
    ...(compatible ? [`; print_compatible_printers = "${compatible}"`] : []),
    "; print_settings_id = 0.20mm Standard",
    ...extraConfig,
    "; CONFIG_BLOCK_END",
  ] : [];
  return Buffer.from([...head, ...body, pad, ...cfg, ""].join("\n"), "utf8");
}

module.exports = { gcodeFile, PNG_1x1, thumb };
