// test/library/gcodeExtract.test.js — what the Library reads out of G-code
// (docs/library-design.md §6.2), on synthetic files shaped like the real
// ones: Orca/Snapmaker Orca headers, EXCLUDE_OBJECT_DEFINE instances,
// "; printing object" lines, thumbnails, and a config block at the end.
const test = require("node:test");
const assert = require("node:assert/strict");
const X = require("../../library/gcodeExtract");
const { gcodeFile, PNG_1x1 } = require("./helpers/gcode");

test("a complete file: generator, identity, profile, palette, time, weight, objects, copies, thumbnail", () => {
  const buf = gcodeFile({ printerModel: "Snapmaker U1", settingsId: "PixelPrints U1 (0.4mm)", objects: [["Kitty.stl", 2], ["Base.stl", 1]] });
  const r = X.extractFromWindow(buf, null, { wholeFile: true });
  assert.equal(r.slicer, "OrcaSlicer");
  assert.equal(r.slicerVersion, "2.4.2");
  assert.equal(r.identity.printerModel, "Snapmaker U1");
  assert.equal(r.identity.printerSettingsId, "PixelPrints U1 (0.4mm)");
  assert.equal(r.variant.layer_height, 0.2);
  assert.equal(r.variant.nozzle, 0.4);
  assert.equal(r.variant.est_seconds, 5 * 3600 + 41 * 60 + 12);
  assert.equal(r.variant.weight_g, 104.55);
  assert.equal(r.variant.config_block, 1);
  assert.equal(r.variant.copies, 2, "the most instances of one object; two different objects are parts, not copies");
  const kitty = r.objects.find(o => o.norm === "kitty" && o.origin === "exclude_object");
  assert.equal(kitty.copies, 2);
  assert.match(kitty.excerpt, /^EXCLUDE_OBJECT_DEFINE NAME=Kitty\.stl_id_0_copy_0/);
  assert.ok(kitty.excerpt.length <= 200);
  assert.ok(r.objects.some(o => o.origin === "printing_object" && o.norm === "kitty"), "'; printing object' lines are read too");
  assert.equal(r.thumbnail.mime, "image/png");
  assert.equal(r.thumbnail.w, 300, "the largest thumbnail is kept");
  assert.deepEqual([...r.thumbnail.data], [...PNG_1x1]);
  assert.equal(r.excerpts.printer_model, "; printer_model = Snapmaker U1");
});

test("generic object names are marked and never lost", () => {
  for (const n of ["Assembly", "Part 3", "object", "12", "Body_id_0_copy_0"]) assert.equal(X.normaliseObjectName(n).generic, true, n);
  for (const n of ["MMM_Beardie_Body_v08R.stl_id_1_copy_0", "HollowLog", "Flexy_Grinch_Standard_STL_No Hat Version2.stl"]) assert.equal(X.normaliseObjectName(n).generic, false, n);
  for (const n of ["3DBenchy", "3DBenchy.stl_id_0_copy_0", "Calibration Cube"]) assert.equal(X.normaliseObjectName(n).generic, true, n + ": a common test print (§6.3)");
  assert.equal(X.normaliseObjectName("MMM_Beardie_Body_v08R.stl id:1 copy 0").norm, "mmm beardie body v08r");
});

test("M486 object names are read", () => {
  const r = X.extractFromWindow(Buffer.from('M486 S0 A"Left bracket"\nM486 S1 A"Right bracket"\nG1 X1 Y1\n'), null, { wholeFile: true });
  assert.deepEqual(r.objects.map(o => o.norm).sort(), ["left bracket", "right bracket"]);
});

test("the window grows while the head ends inside a thumbnail or before the print body, and while the tail has no config", () => {
  const full = gcodeFile({ printerModel: "Snapmaker U1" });
  const s = full.toString("latin1");
  const inThumb = Buffer.from(s.slice(0, s.indexOf("; thumbnail end")), "latin1");
  assert.equal(X.windowNeeds(inThumb, Buffer.from("; printer_model = X\n")).growHead, true);
  assert.equal(X.windowNeeds(inThumb, Buffer.from("; printer_model = X\n")).openThumbnail, true);
  const beforeBody = Buffer.from(s.slice(0, s.indexOf("; EXECUTABLE_BLOCK_START")), "latin1");
  assert.equal(X.windowNeeds(beforeBody, Buffer.from("; CONFIG_BLOCK_START\n")).growHead, true);
  assert.equal(X.windowNeeds(full, Buffer.from("G1 X1\n")).growTail, false, "the head holds the config: nothing to grow");
  const head = Buffer.from(s.slice(0, s.indexOf("; CONFIG_BLOCK_START")), "latin1");
  assert.equal(X.windowNeeds(head, Buffer.from("G1 X1 Y2\nG1 X2 Y3\n")).growTail, true);
  assert.equal(X.windowNeeds(head, Buffer.from("; CONFIG_BLOCK_START\n; printer_model = U1\n")).growTail, false);
});

test("a file with no config block gives nulls, not guesses", () => {
  const r = X.extractFromWindow(Buffer.from("; generated by Cura_SteamEngine 5.0 on 2024-01-01 at 10:00:00\nG1 X1 Y1\n"), null, { wholeFile: true });
  assert.equal(r.variant.config_block, 0);
  assert.equal(r.identity.printerModel, null);
  assert.equal(r.variant.est_seconds, null);
  assert.equal(r.thumbnail, null);
});

test("a line cut by the window edge is dropped, not half-read", () => {
  const head = Buffer.from("; printer_model = Snapmaker U1\nG1 X1 Y1\n; printer_settings_id = Pixel");
  const tail = Buffer.from("ints U1\n; layer_height = 0.2\n");
  const r = X.extractFromWindow(head, tail);
  assert.equal(r.identity.printerModel, "Snapmaker U1");
  assert.equal(r.identity.printerSettingsId, null, "neither half of the cut line is taken for a value");
  assert.equal(r.variant.layer_height, 0.2);
});

test("the streamed extractor gives the same answer as the window", () => {
  const buf = gcodeFile({ printerModel: "Flashforge AD5X", settingsId: "AD5X (PixelPrints, 0.4)", objects: [["Beardie.stl", 1]] });
  const ex = X.createExtractor();
  for (const l of buf.toString("utf8").split(/\r?\n/)) ex.feed(l);
  const a = ex.result(), b = X.extractFromWindow(buf, null, { wholeFile: true });
  assert.deepEqual({ ...a, thumbnail: null, lines: 0 }, { ...b, thumbnail: null, lines: 0 });
});

test("durations parse the slicers' forms", () => {
  assert.equal(X.parseDuration("1d 2h 3m 4s"), 93784);
  assert.equal(X.parseDuration("51m 47s"), 3107);
  assert.equal(X.parseDuration(""), null);
  assert.deepEqual(X.splitGenerator("Creality_Print V7.0.0.4127"), { slicer: "Creality_Print", version: "7.0.0.4127" });
  assert.deepEqual(X.splitGenerator("Snapmaker Orca 2.3.5"), { slicer: "Snapmaker Orca", version: "2.3.5" });
});

test("Creality thumbnail block forms are recognised and their pictures kept; their data is never read as config", () => {
  // The block headers of real Creality files: Creality Print's
  // "; png begin 96*96 …" and "; thumbnail begin 300 300 …" (no "x").
  const b64 = PNG_1x1.toString("base64");
  const text = [
    "; THUMBNAIL_BLOCK_START",
    "; png begin 96*96 5728 4 78 819", "; " + b64, "; png end",
    "; thumbnail begin 300 300 44376", "; " + b64, "; thumbnail end",
    "; THUMBNAIL_BLOCK_END",
    "G1 X1 Y1",
    "; printer_model = Creality Ender-3 V3 Plus",
  ].join("\n");
  const r = X.extractFromWindow(Buffer.from(text), null, { wholeFile: true });
  assert.deepEqual(r.thumbnails.map(t => [t.w, t.h]), [[96, 96], [300, 300]]);
  assert.equal(r.thumbnail.w, 300);
  assert.deepEqual([...r.thumbnail.data], [...PNG_1x1]);
  assert.equal(r.identity.printerModel, "Creality Ender-3 V3 Plus");
  assert.equal(X.windowNeeds(Buffer.from(text.split("; png end")[0]), null).openThumbnail, true);
});

test("thumbnail data that does not decode to a PNG or JPEG gives no picture rather than a broken one, and is not read as config", () => {
  const text = ["; png begin 96*96 10", "; notbase64png=", "; png end", "G1 X1 Y1", "; layer_height = 0.2"].join("\n");
  const r = X.extractFromWindow(Buffer.from(text), null, { wholeFile: true });
  assert.equal(r.thumbnails.length, 1);
  assert.equal(r.thumbnail, null);
  assert.equal(r.variant.layer_height, 0.2);
  assert.equal(Object.keys(r.excerpts).length, 0);
});
